function activePlanPath() {
  const guide = fs.readFileSync(docsGuidePath, "utf8");
  const match = guide.match(
    /Milestone \d+,\s*\[[^\]]+\]\((milestones\/[^)]+\/plan\.html)\),\s*is active\./u,
  );
  if (!match) {
    throw new Error("docs/README.md must identify one active milestone plan.");
  }
  return path.join(docsDirectory, ...match[1].split("/"));
}

function validateSectionOrder(plan, planPath) {
  let previousIndex = -1;
  requiredPlanSections.forEach((section) => {
    const marker = `<h2>${section}</h2>`;
    const sectionIndex = plan.indexOf(marker);
    if (sectionIndex < 0) {
      throw new Error(`${toPosixRelative(planPath)} is missing ${marker}.`);
    }
    if (sectionIndex <= previousIndex) {
      throw new Error(`${toPosixRelative(planPath)} has milestone sections out of order.`);
    }
    previousIndex = sectionIndex;
  });
}

function validateWorkProgress(plan, planPath) {
  const statuses = [...plan.matchAll(/<details class="work-item" data-status="([^"]+)"/gu)]
    .map((match) => match[1]);
  if (statuses.length === 0) {
    throw new Error(`${toPosixRelative(planPath)} must define trackable work items.`);
  }
  const invalidStatus = statuses.find((status) => !validWorkStatuses.has(status));
  if (invalidStatus) {
    throw new Error(`${toPosixRelative(planPath)} uses invalid work status: ${invalidStatus}.`);
  }

  const progress = plan.match(/Milestone work packages completed: (\d+) of (\d+)/u);
  if (!progress) {
    throw new Error(`${toPosixRelative(planPath)} must expose aggregate milestone progress.`);
  }
  const doneCount = statuses.filter((status) => status === "done").length;
  const reportedDone = Number(progress[1]);
  const reportedTotal = Number(progress[2]);
  if (reportedDone !== doneCount || reportedTotal !== statuses.length) {
    throw new Error(
      `${toPosixRelative(planPath)} reports ${reportedDone}/${reportedTotal} progress but contains ${doneCount}/${statuses.length} completed work items.`,
    );
  }
}

function validateActivePlan() {
  const planPath = activePlanPath();
  if (!fs.existsSync(planPath)) {
    throw new Error(`Active milestone plan does not exist: ${toPosixRelative(planPath)}.`);
  }
  const plan = fs.readFileSync(planPath, "utf8");
  validateSectionOrder(plan, planPath);
  validateWorkProgress(plan, planPath);

  const requiredMarkers = [
    "data-completion-usage",
    "<strong>Starting state:</strong>",
    "<strong>Proposed execution:</strong>",
    "<strong>Success signal:</strong>",
    "data-shared-planning-contract",
    "data-milestone-contract",
    'src="../planning-contract.html"',
  ];
  requiredMarkers.forEach((marker) => {
    if (!plan.includes(marker)) {
      throw new Error(`${toPosixRelative(planPath)} is missing required marker: ${marker}.`);
    }
  });
  return planPath;
}

function run({ check }) {
  const source = fs.readFileSync(contractSourcePath, "utf8");
  const rendered = renderContract(source);
  if (check) {
    const current = fs.existsSync(contractOutputPath)
      ? fs.readFileSync(contractOutputPath, "utf8")
      : null;
    if (current !== rendered) {
      throw new Error(
        "docs/milestones/planning-contract.html is stale; run `npm run docs:milestones`.",
      );
    }
  } else {
    fs.mkdirSync(path.dirname(contractOutputPath), { recursive: true });
    fs.writeFileSync(contractOutputPath, rendered, "utf8");
    console.log(`Rendered ${toPosixRelative(contractOutputPath)}`);
  }

  const planPath = validateActivePlan();
  console.log(`Validated ${toPosixRelative(planPath)}`);
}

try {
  run({ check: process.argv.includes("--check") });
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
