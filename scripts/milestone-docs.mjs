import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { marked } from "marked";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, "..");
const docsDirectory = path.join(projectRoot, "docs");
const milestoneDirectory = path.join(docsDirectory, "milestones");
const contractSourcePath = path.join(milestoneDirectory, "README.md");
const contractOutputPath = path.join(milestoneDirectory, "planning-contract.html");
const docsGuidePath = path.join(docsDirectory, "README.md");
const validWorkStatuses = new Set(["pending", "active", "blocked", "done"]);
const requiredPlanSections = [
  "High-Level Objective",
  "Completion Usage",
  "Baseline",
  "Current Delivery Horizon",
  "Work Plan",
  "Scope Boundaries",
  "Risks And Controls",
  "Exit Criteria",
  "Decision Log",
];

function toPosixRelative(targetPath) {
  return path.relative(projectRoot, targetPath).split(path.sep).join("/");
}

function contractDigest(source) {
  return crypto.createHash("sha256").update(source, "utf8").digest("hex");
}

